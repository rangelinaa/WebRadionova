$regiony_i_goroda = [
    "Тюменская область" => ["Тюмень", "Тобольск", "Ишим", "Ялуторовск", "Заводоуковск"],
    "Московская область" => ["Москва", "Зеленоград", "Клин"],
    "Ленинградская область" => ["Санкт-Петербург", "Всеволожск", "Павловск", "Кронштадт"],
    "Рязанская область" => ["Рязань", "Касимов", "Скопин", "Сасово", "Ряжск"],
];
 
foreach ($regiony_i_goroda as $oblast => $goroda) {
    $goroda_na_k = array_filter($goroda, fn($g) => mb_substr($g, 0, 1, 'UTF-8') === 'К');
 
    if (!empty($goroda_na_k)) {
        echo $oblast . "\n";
        echo implode(", ", $goroda_na_k) . "\n\n";
    }
}

